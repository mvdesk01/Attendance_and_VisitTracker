  final String staffCode;
  final String staffName;
  final String visitLocation;
  final String visitPurpose;
  final String flagValue;
  final String advanceTaken;
  final String calculateExpense;
  final String balanceAmount;
  final String expenditureDate;
  final String amount;
  final String expenditureDetails;
